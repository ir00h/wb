use std::path::Path;

use oxc_allocator::Allocator;
use oxc_parser::Parser;
use oxc_span::SourceType;
use ra_ap_rustc_lexer::{FrontmatterAllowed, TokenKind, tokenize};

use crate::finding::{self, Finding, line_of};

const FIX: &str = "say it in code: a name, a type, a test";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Syntax {
    Rust,
    Script,
    Css,
    Markup,
    Toml,
    Yaml,
    Shell,
    IgnoreList,
    Json,
    Plain,
    Binary,
}

enum Directive {
    Line(&'static str),
    Shebang,
}

struct Allowance {
    files: &'static str,
    directive: Directive,
    reason: &'static str,
}

const ALLOWED: &[Allowance] = &[
    Allowance {
        files: "Cargo.lock",
        directive: Directive::Line("# This file is automatically @generated by Cargo."),
        reason: "Cargo writes this header on every lock file update",
    },
    Allowance {
        files: "Cargo.lock",
        directive: Directive::Line("# It is not intended for manual editing."),
        reason: "Cargo writes this header on every lock file update",
    },
    Allowance {
        files: "*.sh",
        directive: Directive::Shebang,
        reason: "the system reads the interpreter of an executable script from its first line",
    },
];

fn syntax_of(path: &str) -> Option<Syntax> {
    let name = path.rsplit('/').next().unwrap_or(path);
    let by_name = match name {
        "Cargo.lock" => Some(Syntax::Toml),
        ".gitignore" | ".gitattributes" => Some(Syntax::IgnoreList),
        ".node-version" | "LICENSE" => Some(Syntax::Plain),
        _ => None,
    };
    if by_name.is_some() {
        return by_name;
    }
    let extension = name.rsplit_once('.').map(|(_, extension)| extension)?;
    Some(match extension {
        "rs" => Syntax::Rust,
        "ts" | "tsx" | "mts" | "cts" | "js" | "jsx" | "mjs" | "cjs" => Syntax::Script,
        "css" => Syntax::Css,
        "html" | "md" => Syntax::Markup,
        "toml" => Syntax::Toml,
        "yml" | "yaml" => Syntax::Yaml,
        "sh" => Syntax::Shell,
        "json" => Syntax::Json,
        "txt" => Syntax::Plain,
        "png" | "icns" | "ico" => Syntax::Binary,
        _ => return None,
    })
}

fn is_allowed(path: &str, line: usize, line_text: &str) -> bool {
    ALLOWED.iter().any(|allowance| {
        let file_matches = match allowance.files.strip_prefix('*') {
            Some(suffix) => path.ends_with(suffix),
            None => path == allowance.files,
        };
        let directive_matches = match allowance.directive {
            Directive::Line(exact) => line_text == exact,
            Directive::Shebang => line == 1 && line_text.starts_with("#!"),
        };
        file_matches && directive_matches
    })
}

pub fn check(root: &Path) -> Result<(), String> {
    let mut findings = Vec::new();
    for path in finding::tracked_files(root)? {
        let full = root.join(&path);
        if !full.is_file() {
            continue;
        }
        let Some(syntax) = syntax_of(&path) else {
            findings.push(Finding::new(
                &path,
                1,
                "the comments check has no rule for this file type; teach it the comment syntax",
            ));
            continue;
        };
        if syntax == Syntax::Binary {
            continue;
        }
        match std::fs::read_to_string(&full) {
            Ok(text) => findings.extend(comments_in(&path, &text)),
            Err(error) => findings.push(Finding::new(&path, 1, format!("unreadable: {error}"))),
        }
    }
    finding::report(&findings).map_err(|report| format!("{report}\n\n{}", allow_list()))
}

fn allow_list() -> String {
    let entries: Vec<String> = ALLOWED
        .iter()
        .map(|allowance| {
            let directive = match allowance.directive {
                Directive::Line(exact) => exact,
                Directive::Shebang => "#! on the first line",
            };
            format!(
                "  {}: `{directive}` because {}",
                allowance.files, allowance.reason
            )
        })
        .collect();
    format!("allowed directives:\n{}", entries.join("\n"))
}

fn comments_in(path: &str, text: &str) -> Vec<Finding> {
    let offsets = match syntax_of(path) {
        Some(Syntax::Rust) => rust_comments(text),
        Some(Syntax::Script) => match script_comments(path, text) {
            Ok(offsets) => offsets,
            Err(message) => return vec![Finding::new(path, 1, message)],
        },
        Some(Syntax::Css) => css_comments(text),
        Some(Syntax::Markup) => text.match_indices("<!--").map(|(at, _)| at).collect(),
        Some(Syntax::Toml) => toml_comments(text),
        Some(Syntax::Yaml) => yaml_comments(text),
        Some(Syntax::Shell) => shell_comments(text),
        Some(Syntax::IgnoreList) => ignore_list_comments(text),
        Some(Syntax::Json) => return json_findings(path, text),
        Some(Syntax::Plain | Syntax::Binary) | None => Vec::new(),
    };
    offsets
        .into_iter()
        .filter_map(|offset| {
            let line = line_of(text, offset);
            let line_text = text.lines().nth(line - 1).unwrap_or("").trim();
            if is_allowed(path, line, line_text) {
                return None;
            }
            let snippet: String = text[offset..]
                .lines()
                .next()
                .unwrap_or("")
                .trim()
                .chars()
                .take(60)
                .collect();
            Some(Finding::new(
                path,
                line,
                format!("comment `{snippet}` is not allowed; {FIX}"),
            ))
        })
        .collect()
}

fn rust_comments(text: &str) -> Vec<usize> {
    let mut offsets = Vec::new();
    let mut significant = Vec::new();
    let mut offset = 0;
    for token in tokenize(text, FrontmatterAllowed::No) {
        let length = token.len as usize;
        match token.kind {
            TokenKind::LineComment { .. } | TokenKind::BlockComment { .. } => offsets.push(offset),
            TokenKind::Whitespace => {}
            kind => significant.push((kind, offset, &text[offset..offset + length])),
        }
        offset += length;
    }
    offsets.extend(doc_attributes(&significant));
    offsets.sort_unstable();
    offsets
}

fn doc_attributes(tokens: &[(TokenKind, usize, &str)]) -> Vec<usize> {
    let mut offsets = Vec::new();
    let mut attribute: Option<(usize, usize)> = None;
    for (index, &(kind, offset, token_text)) in tokens.iter().enumerate() {
        match (attribute, kind) {
            (None, TokenKind::Pound) => {
                let mut next = index + 1;
                if matches!(tokens.get(next), Some((TokenKind::Bang, _, _))) {
                    next += 1;
                }
                if matches!(tokens.get(next), Some((TokenKind::OpenBracket, _, _))) {
                    attribute = Some((offset, 0));
                }
            }
            (Some((start, depth)), TokenKind::OpenBracket) => attribute = Some((start, depth + 1)),
            (Some((start, depth)), TokenKind::CloseBracket) => {
                attribute = (depth > 1).then_some((start, depth - 1));
            }
            (Some((start, _)), TokenKind::Ident)
                if token_text == "doc"
                    && matches!(tokens.get(index + 1), Some((TokenKind::Eq, _, _))) =>
            {
                offsets.push(start);
            }
            _ => {}
        }
    }
    offsets
}

fn script_comments(path: &str, text: &str) -> Result<Vec<usize>, String> {
    let source_type = SourceType::from_path(path)
        .map_err(|error| format!("cannot tell the script dialect: {error}"))?;
    let allocator = Allocator::default();
    let parsed = Parser::new(&allocator, text, source_type).parse();
    if let Some(error) = parsed.errors.first() {
        return Err(format!(
            "cannot be parsed, so its comments cannot be checked: {error}"
        ));
    }
    Ok(parsed
        .program
        .comments
        .iter()
        .map(|comment| comment.span.start as usize)
        .collect())
}

fn json_findings(path: &str, text: &str) -> Vec<Finding> {
    match serde_json::from_str::<serde_json::Value>(text) {
        Ok(_) => Vec::new(),
        Err(error) => vec![Finding::new(
            path,
            error.line(),
            format!("is not strict JSON ({error}); JSON carries no comments, {FIX}"),
        )],
    }
}

fn css_comments(text: &str) -> Vec<usize> {
    let bytes = text.as_bytes();
    let mut offsets = Vec::new();
    let mut quote: Option<u8> = None;
    let mut index = 0;
    while index < bytes.len() {
        let byte = bytes[index];
        match quote {
            Some(_) if byte == b'\\' => index += 1,
            Some(open) if byte == open => quote = None,
            None if byte == b'"' || byte == b'\'' => quote = Some(byte),
            None if bytes[index..].starts_with(b"/*") => {
                offsets.push(index);
                index = text[index + 2..]
                    .find("*/")
                    .map_or(bytes.len(), |end| index + 2 + end + 1);
            }
            _ => {}
        }
        index += 1;
    }
    offsets
}

fn toml_comments(text: &str) -> Vec<usize> {
    let bytes = text.as_bytes();
    let mut offsets = Vec::new();
    let mut closer: Option<&[u8]> = None;
    let mut index = 0;
    while index < bytes.len() {
        let rest = &bytes[index..];
        match closer {
            Some(end) if rest.starts_with(end) => {
                index += end.len();
                closer = None;
                continue;
            }
            Some(end) if rest[0] == b'\\' && end[0] == b'"' => index += 1,
            Some(end) if rest[0] == b'\n' && end.len() == 1 => closer = None,
            Some(_) => {}
            None => {
                let opener: Option<&[u8]> = [&b"\"\"\""[..], b"'''", b"\"", b"'"]
                    .into_iter()
                    .find(|opener| rest.starts_with(opener));
                if let Some(opener) = opener {
                    closer = Some(opener);
                    index += opener.len();
                    continue;
                }
                if rest[0] == b'#' {
                    offsets.push(index);
                    index += rest
                        .iter()
                        .position(|&byte| byte == b'\n')
                        .unwrap_or(rest.len());
                    continue;
                }
            }
        }
        index += 1;
    }
    offsets
}

fn follows_space(bytes: &[u8], index: usize) -> bool {
    index == 0 || bytes[index - 1].is_ascii_whitespace()
}

fn yaml_comments(text: &str) -> Vec<usize> {
    let bytes = text.as_bytes();
    let mut offsets = Vec::new();
    let mut quote: Option<u8> = None;
    let mut index = 0;
    while index < bytes.len() {
        let byte = bytes[index];
        match quote {
            Some(b'"') if byte == b'\\' => index += 1,
            Some(b'\'') if bytes[index..].starts_with(b"''") => index += 1,
            Some(open) if byte == open => quote = None,
            None if (byte == b'"' || byte == b'\'')
                && (follows_space(bytes, index) || b"[{,".contains(&bytes[index - 1])) =>
            {
                quote = Some(byte);
            }
            None if byte == b'#' && follows_space(bytes, index) => {
                offsets.push(index);
                index += bytes[index..]
                    .iter()
                    .position(|&next| next == b'\n')
                    .unwrap_or(bytes.len() - index);
                continue;
            }
            _ => {}
        }
        index += 1;
    }
    offsets
}

fn shell_comments(text: &str) -> Vec<usize> {
    let bytes = text.as_bytes();
    let mut offsets = Vec::new();
    let mut quote: Option<u8> = None;
    let mut index = 0;
    while index < bytes.len() {
        let byte = bytes[index];
        match quote {
            Some(b'"') | None if byte == b'\\' => index += 1,
            Some(open) if byte == open => quote = None,
            None if byte == b'"' || byte == b'\'' => quote = Some(byte),
            None if byte == b'#'
                && (follows_space(bytes, index) || b";|&(".contains(&bytes[index - 1])) =>
            {
                offsets.push(index);
                index += bytes[index..]
                    .iter()
                    .position(|&next| next == b'\n')
                    .unwrap_or(bytes.len() - index);
                continue;
            }
            _ => {}
        }
        index += 1;
    }
    offsets
}

fn ignore_list_comments(text: &str) -> Vec<usize> {
    let mut offsets = Vec::new();
    let mut offset = 0;
    for line in text.split_inclusive('\n') {
        if line.starts_with('#') {
            offsets.push(offset);
        }
        offset += line.len();
    }
    offsets
}

#[cfg(test)]
mod tests {
    use super::comments_in;

    fn lines(path: &str, text: &str) -> Vec<usize> {
        comments_in(path, text)
            .into_iter()
            .filter_map(|finding| finding.line)
            .collect()
    }

    #[test]
    fn rust_line_comment_is_reported_with_the_fix() {
        let findings = comments_in("a.rs", "fn main() {}\n// why\n");
        assert_eq!(findings.len(), 1);
        assert_eq!(
            findings[0].to_string(),
            "a.rs:2: comment `// why` is not allowed; say it in code: a name, a type, a test"
        );
    }

    #[test]
    fn rust_strings_that_look_like_comments_are_code() {
        let text = "const URL: &str = \"https://example.org\";\nconst SLASHES: &str = \"//\";\nconst RAW: &str = r#\"/* */\"#;\n";
        assert_eq!(lines("a.rs", text), Vec::<usize>::new());
    }

    #[test]
    fn rust_lifetime_next_to_a_character_literal_is_code() {
        let text =
            "fn pick<'a>(text: &'a str) -> char { let _ = text; '/' }\nconst C: char = '\\'';\n";
        assert_eq!(lines("a.rs", text), Vec::<usize>::new());
    }

    #[test]
    fn rust_nested_block_comment_is_one_comment() {
        let text = "fn a() {}\n/* outer /* inner */ still outer */\nfn b() {}\n";
        assert_eq!(lines("a.rs", text), vec![2]);
    }

    #[test]
    fn rust_doc_comments_and_doc_attributes_are_comments() {
        let text = "//! crate\n/// item\nstruct A;\n/** block */\nstruct B;\n#[doc = \"text\"]\nstruct C;\n#![doc = \"inner\"]\n#[doc(hidden)]\nstruct D;\n#[cfg_attr(test, doc = \"x\")]\nstruct E;\n";
        assert_eq!(lines("a.rs", text), vec![1, 2, 4, 6, 8, 11]);
    }

    #[test]
    fn script_strings_regex_and_templates_are_code() {
        let text = "const url = \"https://example.org\";\nconst slashes = '//';\nconst pattern = /\\/\\/+/g;\nconst template = `/* ${url} */ // not a comment`;\n";
        assert_eq!(lines("a.ts", text), Vec::<usize>::new());
    }

    #[test]
    fn script_block_and_line_comments_are_reported() {
        let text = "/** docs */\nexport const a = 1;\nexport const b = 2; // trailing\n";
        assert_eq!(lines("a.ts", text), vec![1, 3]);
    }

    #[test]
    fn jsx_comment_is_a_comment_and_jsx_text_is_not() {
        let text = "export const A = () => (\n  <div>\n    {/* hidden */}\n    https://example.org // text\n  </div>\n);\n";
        assert_eq!(lines("a.tsx", text), vec![3]);
    }

    #[test]
    fn unparsable_script_is_reported() {
        let findings = comments_in("a.ts", "const = ;\n");
        assert_eq!(findings.len(), 1);
        assert!(findings[0].message.starts_with("cannot be parsed"));
    }

    #[test]
    fn css_comment_is_reported_and_strings_are_not() {
        let text = "a { background: url(\"https://example.org/x.png\"); }\n/* note */\nb::after { content: \"/* */\"; }\n";
        assert_eq!(lines("a.css", text), vec![2]);
    }

    #[test]
    fn markup_comments_are_reported() {
        assert_eq!(lines("a.html", "<p>x</p>\n<!-- why -->\n"), vec![2]);
        assert_eq!(lines("a.md", "# Title\n\n<!-- hidden -->\n"), vec![3]);
    }

    #[test]
    fn toml_hash_inside_strings_is_code() {
        let text = "a = \"#000\"\nb = 'x#y'\nc = \"\"\"\nmulti # line\n\"\"\"\nd = 1 # trailing\n# full line\n";
        assert_eq!(lines("a.toml", text), vec![6, 7]);
    }

    #[test]
    fn yaml_hash_inside_quotes_or_words_is_code() {
        let text = "a: \"#000\"\nb: '#fff'\nc: x#y\nd: it's # trailing\n# full line\n";
        assert_eq!(lines("a.yml", text), vec![4, 5]);
    }

    #[test]
    fn shell_shebang_is_allowed_and_other_hashes_are_checked() {
        let text = "#!/bin/sh\necho \"#1\" ${#name} $#\necho done # why\n";
        assert_eq!(lines("tools/run.sh", text), vec![3]);
    }

    #[test]
    fn ignore_list_comment_is_a_line_starting_with_a_hash() {
        assert_eq!(lines(".gitignore", "target/\n# why\n\\#literal\n"), vec![2]);
    }

    #[test]
    fn json_must_be_strict() {
        assert_eq!(
            lines("a.json", "{\"a\": \"// fine\"}\n"),
            Vec::<usize>::new()
        );
        assert_eq!(lines("a.json", "{\n  // no\n  \"a\": 1\n}\n"), vec![2]);
    }

    #[test]
    fn cargo_lock_header_is_allowed_and_nothing_else() {
        let text = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n# extra\n";
        assert_eq!(lines("Cargo.lock", text), vec![4]);
        assert_eq!(
            lines(
                "other.toml",
                "# This file is automatically @generated by Cargo.\n"
            ),
            vec![1]
        );
    }
}
