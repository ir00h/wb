const CALLS_FILE: &str = "Calls.ts";

fn variant_tags(union: &str) -> Vec<String> {
    union
        .split("\"type\": \"")
        .skip(1)
        .filter_map(|rest| rest.split('"').next())
        .map(str::to_owned)
        .collect()
}

fn quoted(items: &[String]) -> String {
    items
        .iter()
        .map(|item| format!("\"{item}\""))
        .collect::<Vec<_>>()
        .join(", ")
}

fn crossing_types(config: &Config) -> BTreeMap<TypeId, String> {
    fn named<T: TS + 'static>(config: &Config) -> (TypeId, String) {
        (TypeId::of::<T>(), T::name(config))
    }
    BTreeMap::from([
        (TypeId::of::<()>(), "null".to_owned()),
        named::<Boards>(config),
        named::<OpenBoard>(config),
        named::<BoardSnapshot>(config),
        named::<ApplyOp>(config),
        named::<Outcome>(config),
        named::<BoardUpdate>(config),
        named::<CloseAnswer>(config),
        named::<BoardHealth>(config),
    ])
}

fn ts_name(types: &BTreeMap<TypeId, String>, call: &str, id: TypeId) -> Result<String, String> {
    types.get(&id).cloned().ok_or_else(|| {
        format!(
            "the call `{call}` of the call table uses a type that crossing_types in crates/xtask/src/bindings.rs does not name; add it there and to export_every_type"
        )
    })
}

fn import_order(name: &str) -> Vec<(char, bool)> {
    name.chars()
        .map(|letter| (letter.to_ascii_lowercase(), letter.is_ascii_lowercase()))
        .collect()
}

fn calls_file(config: &Config) -> Result<String, String> {
    let types = crossing_types(config);
    let mut imports = BTreeSet::new();
    let mut entries = Vec::new();
    for shape in wb_model::call_shapes() {
        let args = ts_name(&types, shape.name, shape.args)?;
        let reply = ts_name(&types, shape.name, shape.reply)?;
        entries.push(format!(
            "  {}: {{ args: {args}, reply: {reply} }};",
            shape.name
        ));
        imports.extend([args, reply]);
    }
    let mut events = Vec::new();
    for shape in wb_model::event_shapes() {
        let payload = ts_name(&types, shape.name, shape.args)?;
        events.push(format!("  {}: {payload};", shape.name));
        imports.insert(payload);
    }
    imports.remove("null");
    let mut imports: Vec<String> = imports.into_iter().collect();
    imports.sort_by_key(|name| import_order(name));
    let mut lines: Vec<String> = imports
        .iter()
        .map(|name| format!("import type {{ {name} }} from \"./{name}\";"))
        .collect();
    lines.push(String::new());
    lines.push("export type Calls = {".to_owned());
    lines.extend(entries);
    lines.push("};".to_owned());
    lines.push(String::new());
    lines.push("export type Events = {".to_owned());
    lines.extend(events);
    lines.push("};".to_owned());
    lines.push(String::new());
    lines.push(format!(
        "export const ERROR_TYPES = [{}] as const;",
        quoted(&variant_tags(&Error::inline(config)))
    ));
    lines.push(String::new());
    lines.push(format!(
        "export const TITLE_BAR = {{ height: {}, buttonsX: {}, buttonsY: {}, contentInset: {} }} as const;",
        TITLE_BAR.height, TITLE_BAR.buttons_x, TITLE_BAR.buttons_y, TITLE_BAR.content_inset
    ));
    Ok(format!("{}\n", lines.join("\n")))
}

fn config(out_dir: &Path) -> Config {
    Config::new()
        .with_out_dir(out_dir)
        .with_large_int("number".to_owned())
}

fn normalize(text: &str) -> String {
    let body: Vec<&str> = text
        .lines()
        .skip_while(|line| line.contains(GENERATOR_MARK) || line.trim().is_empty())
        .collect();
    format!("{}\n", body.join("\n").trim_end())
}

fn brand_problems(files: &Files) -> Vec<String> {
    let mut problems = Vec::new();
    for text in files.values() {
        for line in text.lines() {
            let Some(declaration) = line.strip_prefix("export type ") else {
                continue;
            };
            let Some((name, definition)) = declaration.split_once(" = ") else {
                continue;
            };
            let Some((_, after)) = definition.split_once("__brand: \"") else {
                continue;
            };
            let brand = after.split('"').next().unwrap_or_default();
            if brand != name {
                problems.push(format!(
                    "the id type {name} carries the brand \"{brand}\"; make the brand its own name in wb-model"
                ));
            }
        }
    }
    problems
}

fn read_folder(folder: &Path) -> Result<Files, String> {
    let mut files = Files::new();
    if !folder.is_dir() {
        return Ok(files);
    }
    let mut pending = vec![folder.to_path_buf()];
    while let Some(current) = pending.pop() {
        let entries = fs::read_dir(&current)
            .map_err(|error| format!("cannot read {}: {error}", current.display()))?;
        for entry in entries {
            let path = entry.map_err(|error| error.to_string())?.path();
            if path.is_dir() {
                pending.push(path);
                continue;
            }
            let relative = path
                .strip_prefix(folder)
                .map_err(|error| error.to_string())?
                .to_string_lossy()
                .replace('\\', "/");
            let text = fs::read_to_string(&path)
                .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
            files.insert(relative, text);
        }
    }
    Ok(files)
}

fn scratch_folder() -> Result<PathBuf, String> {
    let stamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_nanos());
    let folder = std::env::temp_dir().join(format!("wb-bindings-{}-{stamp}", std::process::id()));
    fs::create_dir_all(&folder)
        .map_err(|error| format!("cannot create {}: {error}", folder.display()))?;
    Ok(folder)
}

fn generate() -> Result<Files, String> {
    let scratch = scratch_folder()?;
    let exported = export_every_type(&config(&scratch))
        .map_err(|error| format!("exporting the Rust types failed: {error}"));
    let files = exported.and_then(|()| read_folder(&scratch));
    let _ = fs::remove_dir_all(&scratch);
    let mut files: Files = files?
        .into_iter()
        .map(|(path, text)| (path, normalize(&text)))
        .collect();
    files.insert(CALLS_FILE.to_owned(), calls_file(&config(&scratch))?);
    let problems = brand_problems(&files);
    if problems.is_empty() {
        Ok(files)
    } else {
        Err(problems.join("\n"))
    }
}

pub fn write(root: &Path) -> Result<(), String> {
    let files = generate()?;
    let folder = root.join(FOLDER);
    if folder.exists() {
        fs::remove_dir_all(&folder).map_err(|error| format!("cannot clear {FOLDER}: {error}"))?;
    }
    for (relative, text) in &files {
        let path = folder.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|error| error.to_string())?;
        }
        fs::write(&path, text)
            .map_err(|error| format!("cannot write {}: {error}", path.display()))?;
    }
    println!("wrote {} files to {FOLDER}", files.len());
    Ok(())
}

pub fn check(root: &Path) -> Result<(), String> {
    let expected = generate()?;
    let committed = read_folder(&root.join(FOLDER))?;
    let mut reports = Vec::new();
    let problems = drift(&expected, &committed);
    if !problems.is_empty() {
        reports.push(format!(
            "{FOLDER} is out of date with the Rust types:\n\n{}\n\nRegenerate with: {REGENERATE}\nChange the Rust type instead of editing these files.",
            problems.join("\n")
        ));
    }
    if let Err(report) = finding::report(&shape_findings(root, &expected)?) {
        reports.push(report);
    }
    if reports.is_empty() {
        Ok(())
    } else {
        Err(reports.join("\n\n"))
    }
}

fn shape_findings(root: &Path, expected: &Files) -> Result<Vec<finding::Finding>, String> {
    let generated: BTreeSet<String> = expected
        .values()
        .flat_map(|text| shapes::declared_names(text))
        .collect();
    let sources: Vec<(String, String)> = finding::tracked_files(root)?
        .into_iter()
        .filter(|path| {
            path.starts_with(MODEL_FOLDER)
                && !path.starts_with(MODEL_TESTS)
                && Path::new(path)
                    .extension()
                    .is_some_and(|extension| extension == "rs")
        })
        .filter_map(|path| {
            let text = fs::read_to_string(root.join(&path)).ok()?;
            Some((path, text))
        })
        .collect();
    let files: Vec<SourceFile> = sources
        .iter()
        .map(|(path, text)| SourceFile { path, text })
        .collect();
    Ok(shapes::findings(&files, &generated, NEVER_CROSSES))
}

fn first_difference(expected: &str, committed: &str) -> (usize, String, String) {
    let mut expected_lines = expected.lines();
    let mut committed_lines = committed.lines();
    let mut number = 1;
    loop {
        match (expected_lines.next(), committed_lines.next()) {
            (Some(want), Some(have)) if want == have => number += 1,
            (want, have) => {
                let shown = |line: Option<&str>| line.unwrap_or("<no line>").to_owned();
                return (number, shown(have), shown(want));
            }
        }
    }
}

fn drift(expected: &Files, committed: &Files) -> Vec<String> {
    let mut problems = Vec::new();
    for (path, want) in expected {
        match committed.get(path) {
            None => problems.push(format!("- {FOLDER}/{path} is missing")),
            Some(have) if have != want => {
                let (line, have, want) = first_difference(want, have);
                problems.push(format!(
                    "- {FOLDER}/{path} differs at line {line}\n  committed: {have}\n  from Rust: {want}"
                ));
            }
            Some(_) => {}
        }
    }
    for path in committed
        .keys()
        .filter(|path| !expected.contains_key(*path))
    {
        problems.push(format!(
            "- {FOLDER}/{path} is not produced by the Rust types"
        ));
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::{Files, brand_problems, config, drift, generate, normalize};
    use ts_rs::TS;

    fn files(entries: &[(&str, &str)]) -> Files {
        entries
            .iter()
            .map(|(path, text)| ((*path).to_owned(), (*text).to_owned()))
            .collect()
    }

    #[test]
    fn generated_ids_are_branded_strings_without_a_header() {
        let generated = generate().expect("bindings generate");
        assert_eq!(
            generated.get("NoteId.ts").map(String::as_str),
            Some("export type NoteId = string & { readonly __brand: \"NoteId\" };\n")
        );
        assert!(generated.values().all(|text| !text.contains("//")));
    }

    #[test]
    fn large_integers_cross_as_numbers() {
        #[derive(TS)]
        struct Sized {
            #[allow(dead_code)]
            bytes: u64,
        }
        let declaration = Sized::decl(&config(std::path::Path::new(".")));
        assert_eq!(declaration, "type Sized = { bytes: number, };");
    }

    #[test]
    fn header_lines_are_stripped() {
        assert_eq!(
            normalize(
                "// This file was generated by [ts-rs](x). Do not edit this file manually.\n\nexport type A = string;\n"
            ),
            "export type A = string;\n"
        );
    }

    #[test]
    fn a_mistyped_brand_is_reported() {
        let generated = files(&[(
            "NoteId.ts",
            "export type NoteId = string & { readonly __brand: \"NoteID\" };\n",
        )]);
        assert_eq!(
            brand_problems(&generated),
            vec![
                "the id type NoteId carries the brand \"NoteID\"; make the brand its own name in wb-model"
            ]
        );
    }

    #[test]
    fn a_changed_line_is_named_with_both_versions() {
        let expected = files(&[("A.ts", "export type A = { b: number, };\n")]);
        let committed = files(&[("A.ts", "export type A = { c: number, };\n")]);
        assert_eq!(
            drift(&expected, &committed),
            vec![
                "- window/src/bindings/A.ts differs at line 1\n  committed: export type A = { c: number, };\n  from Rust: export type A = { b: number, };"
            ]
        );
    }

    #[test]
    fn missing_and_stray_files_are_named() {
        let expected = files(&[("A.ts", "a\n")]);
        let committed = files(&[("B.ts", "b\n")]);
        assert_eq!(
            drift(&expected, &committed),
            vec![
                "- window/src/bindings/A.ts is missing",
                "- window/src/bindings/B.ts is not produced by the Rust types",
            ]
        );
    }

    #[test]
    fn an_added_line_is_named() {
        let expected = files(&[("A.ts", "a\nb\n")]);
        let committed = files(&[("A.ts", "a\n")]);
        assert_eq!(
            drift(&expected, &committed),
            vec![
                "- window/src/bindings/A.ts differs at line 2\n  committed: <no line>\n  from Rust: b"
            ]
        );
    }
}
